const dictionaries: Record<Lang, Record<Key, string>> = { en, ru };

function readInitialLang(): Lang {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === 'ru' || saved === 'en') return saved;
  } catch {
    // storage unavailable
  }
  return 'ru';
}

let currentLang: Lang = readInitialLang();
const listeners = new Set<() => void>();

export function getLang(): Lang {
  return currentLang;
}

export function setLang(lang: Lang) {
  currentLang = lang;
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch {
    // storage unavailable
  }
  document.documentElement.lang = lang;
  listeners.forEach((l) => l());
}

function subscribe(listener: () => void) {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

/** Translate a key in the current language, substituting {placeholders}. Usable outside React. */
export function t(key: Key | (string & {}), vars?: Record<string, string | number>): string {
  let text = dictionaries[currentLang][key as Key] ?? en[key as Key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.split(`{${k}}`).join(String(v));
    }
  }
  return text;
}

/** Instruction appended to AI prompts so answers come back in the interface language. */
export function aiLanguageInstruction(): string {
  return currentLang === 'ru'
    ? ' Always answer in Russian (keep code, identifiers and code comments in English unless asked otherwise).'
    : '';
}

/** React hook: re-renders the component when the language changes. */
export function useI18n() {
  const lang = useSyncExternalStore(subscribe, getLang, getLang);
  return { lang, setLang, t };
}

document.documentElement.lang = currentLang;
